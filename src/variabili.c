#include <stdio.h>

int main() {
  // dichiarazione di tre variabili
  int i1;
  char c1;
  float f1;
  // assegnazione di un valore alle tre variabili
  i1 = 2;
  c1 = 'A';
  f1 = 3.14;
  // stampa del contenuto delle variabili
  printf("Ecco il contenuto della variabile i1: %d", i1);
  printf("Ecco il contenuto della variabile c1: %c", c1);
  printf("Ecco il contenuto della variabile f1: %f", f1);
}
